//! Pure-Rust port of the SHA-1 collision-detection algorithm (sha1dc),
//! from the vendored `sha1dc/` C sources (MIT licensed; see
//! `sha1dc/LICENSE.txt`).

#![allow(non_upper_case_globals, unused_assignments, unused_parens)]

const K: [u32; 4] = [0x5A827999, 0x6ED9EBA1, 0x8F1BBCDC, 0xCA62C1D6];

fn round_f(round: usize, b: u32, c: u32, d: u32) -> u32 {
    match round / 20 {
        0 => d ^ (b & (c ^ d)),
        1 => b ^ c ^ d,
        2 => (b & c).wrapping_add(d & (b ^ c)),
        _ => b ^ c ^ d,
    }
}

/// Index into the rotating 5-word working vector that plays the role of the
/// macro's formal `a` at compression step `s`.
#[inline]
fn ia(s: usize) -> usize {
    (5 - s % 5) % 5
}

/// One forward compression step using the expanded message `w`.
fn step_fwd(v: &mut [u32; 5], s: usize, w: &[u32]) {
    let a = ia(s);
    let (b, c, d, e) = ((a + 1) % 5, (a + 2) % 5, (a + 3) % 5, (a + 4) % 5);
    let f = round_f(s, v[b], v[c], v[d]);
    v[e] = v[e]
        .wrapping_add(v[a].rotate_left(5))
        .wrapping_add(f)
        .wrapping_add(K[s / 20])
        .wrapping_add(w[s]);
    v[b] = v[b].rotate_left(30);
}

/// One backward (inverse) compression step.
fn step_bwd(v: &mut [u32; 5], s: usize, w: &[u32]) {
    let a = ia(s);
    let (b, c, d, e) = ((a + 1) % 5, (a + 2) % 5, (a + 3) % 5, (a + 4) % 5);
    v[b] = v[b].rotate_right(30);
    let f = round_f(s, v[b], v[c], v[d]);
    v[e] = v[e]
        .wrapping_sub(v[a].rotate_left(5))
        .wrapping_sub(f)
        .wrapping_sub(K[s / 20])
        .wrapping_sub(w[s]);
}

/// Compress `block` (16 words, big-endian) starting from `ihv`, storing the
/// intermediate state before each step and leaving `w` as the expanded
/// message (matching C git's `sha1_compression_states` + `ctx->m1`).
fn compression_states(
    ihv: &mut [u32; 5],
    block: &[u8; 64],
    w: &mut [u32; 80],
    states: &mut [[u32; 5]; 80],
) {
    for t in 0..16 {
        w[t] = u32::from_be_bytes([
            block[t * 4],
            block[t * 4 + 1],
            block[t * 4 + 2],
            block[t * 4 + 3],
        ]);
    }
    for t in 16..80 {
        w[t] = w[t - 3] ^ w[t - 8] ^ w[t - 14] ^ w[t - 16];
        w[t] = w[t].rotate_left(1);
    }
    let mut v = *ihv;
    for t in 0..80 {
        states[t] = v;
        step_fwd(&mut v, t, w);
    }
    for i in 0..5 {
        ihv[i] = ihv[i].wrapping_add(v[i]);
    }
}

/// Compress starting from `ihv` using an already expanded message `w`
/// (C git's `sha1_compression_W`).
fn compression_w(ihv: &mut [u32; 5], w: &[u32]) {
    let mut v = *ihv;
    for t in 0..80 {
        step_fwd(&mut v, t, w);
    }
    *ihv = v;
}

/// Reconstruct the chaining values before/after step `t` for a candidate
/// near-collision message `me2` (C git's `sha1_recompression_step`).
fn recompress(t: usize, me2: &[u32], state: &[u32; 5]) -> ([u32; 5], [u32; 5]) {
    let mut v = *state;
    for s in (0..t).rev() {
        step_bwd(&mut v, s, me2);
    }
    let ihvin = v;
    let mut v = *state;
    for s in t..80 {
        step_fwd(&mut v, s, me2);
    }
    let mut ihvout = ihvin;
    for i in 0..5 {
        ihvout[i] = ihvout[i].wrapping_add(v[i]);
    }
    (ihvin, ihvout)
}

