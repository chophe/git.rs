/// The SHA-1 collision-detecting context (`SHA1_CTX`).
#[derive(Clone)]
pub struct Sha1Dc {
    total: u64,
    ihv: [u32; 5],
    buffer: [u8; 64],
    found_collision: bool,
    safe_hash: bool,
    m1: [u32; 80],
    states: [[u32; 5]; 80],
}

impl Sha1Dc {
    /// Initialize a context (C git configures `safe_hash = 0` by default,
    /// matching `-DSHA1DC_INIT_SAFE_HASH_DEFAULT=0`).
    pub fn new() -> Sha1Dc {
        Sha1Dc {
            total: 0,
            ihv: [0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476, 0xC3D2E1F0],
            buffer: [0; 64],
            found_collision: false,
            safe_hash: false,
            m1: [0; 80],
            states: [[0; 5]; 80],
        }
    }

    fn process(&mut self, block: &[u8; 64]) {
        compression_states(&mut self.ihv, block, &mut self.m1, &mut self.states);

        let mut ubc_dv_mask: u32 = ubc_check(&self.m1);
        if ubc_dv_mask != 0 {
            for dv in SHA1_DVS.iter() {
                if ubc_dv_mask & (1u32 << dv.maskb) == 0 {
                    continue;
                }
                let mut m2 = [0u32; 80];
                for j in 0..80 {
                    m2[j] = self.m1[j] ^ dv.dm[j];
                }
                let (_ihv2, ihvtmp) = recompress(dv.testt, &m2, &self.states[dv.testt]);
                let same = ihvtmp
                    .iter()
                    .zip(self.ihv.iter())
                    .all(|(a, b)| a == b);
                if same {
                    self.found_collision = true;
                    if self.safe_hash {
                        compression_w(&mut self.ihv, &self.m1);
                        compression_w(&mut self.ihv, &self.m1);
                    }
                    ubc_dv_mask = 0;
                    break;
                }
            }
        }
    }

    /// Feed `data` into the context (C git's `SHA1DCUpdate`).
    pub fn update(&mut self, mut data: &[u8]) {
        if data.is_empty() {
            return;
        }
        let mut left = (self.total & 63) as usize;
        if left > 0 && data.len() >= 64 - left {
            let fill = 64 - left;
            self.buffer[left..64].copy_from_slice(&data[..fill]);
            self.total += fill as u64;
            let block = self.buffer;
            self.process(&block);
            data = &data[fill..];
            left = 0;
        }
        while data.len() >= 64 {
            self.total += 64;
            let mut block = [0u8; 64];
            block.copy_from_slice(&data[..64]);
            self.process(&block);
            data = &data[64..];
        }
        if !data.is_empty() {
            self.total += data.len() as u64;
            self.buffer[left..left + data.len()].copy_from_slice(data);
        }
    }

    /// Finalize, returning the 20-byte digest, or `Err` with the digest of
    /// the colliding input when a SHA-1 collision attack was detected
    /// (C git's `SHA1DCFinal` + `git_SHA1DCFinal`).
    pub fn finalize(self) -> Result<[u8; 20], [u8; 20]> {
        self.finish()
    }

    /// Finalize ignoring any collision detection, yielding the raw digest
    /// (which for colliding input is the attacked digest, because safe
    /// hashing is off).
    pub fn finalize_lossy(self) -> [u8; 20] {
        self.finish().unwrap_or_else(|d| d)
    }

    fn finish(mut self) -> Result<[u8; 20], [u8; 20]> {
        let last = (self.total & 63) as usize;
        let padn = if last < 56 { 56 - last } else { 120 - last };
        self.update(&PADDING[..padn]);

        let total = (self.total - padn as u64) << 3;
        self.buffer[56..64].copy_from_slice(&total.to_be_bytes());
        let block = self.buffer;
        self.process(&block);

        let mut output = [0u8; 20];
        for i in 0..5 {
            output[i * 4..i * 4 + 4].copy_from_slice(&self.ihv[i].to_be_bytes());
        }
        if self.found_collision {
            Err(output)
        } else {
            Ok(output)
        }
    }
}

static PADDING: [u8; 64] = {
    let mut p = [0u8; 64];
    p[0] = 0x80;
    p
};

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(h: &[u8]) -> String {
        h.iter().map(|b| format!("{b:02x}")).collect()
    }

    #[test]
    fn empty_matches_known_sha1() {
        let h = Sha1Dc::new().finalize().unwrap();
        assert_eq!(hex(&h), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
    }

    #[test]
    fn abc_matches_known_sha1() {
        let mut h = Sha1Dc::new();
        h.update(b"abc");
        assert_eq!(hex(&h.finalize().unwrap()), "a9993e364706816aba3e25717850c26c9cd0d89d");
    }

    #[test]
    fn shattered_pdf_is_detected() {
        let data = std::fs::read("../../t/t0013/shattered-1.pdf").unwrap();
        let mut h = Sha1Dc::new();
        h.update(&data);
        let digest = h.finalize().unwrap_err();
        assert_eq!(hex(&digest), "38762cf7f55934b34d179ae6a4c80cadccbb7f0a");
    }
}


